help("Select Ubuntu's OpenMPI and its GNU-built parallel library modules.")
whatis("System OpenMPI")
prereq("gfortran")
family("mpi")
local compiler = hierarchyA(myModuleFullName(), 1)[1]
local major = myModuleVersion():match("%d+")
prepend_path("MODULEPATH", pathJoin(os.getenv("MODULEPATH_ROOT"), "MPI", compiler, "openmpi", major))
setenv("MPIROOT", "/usr")
setenv("MPICC", "/usr/bin/mpicc.openmpi")
setenv("MPICXX", "/usr/bin/mpicxx.openmpi")
setenv("MPIFC", "/usr/bin/mpifort.openmpi")
setenv("OMPI_CC", "gcc")
setenv("OMPI_CXX", "g++")
setenv("OMPI_FC", "gfortran")

local multiarch = capture("gcc -print-multiarch"):gsub("%s+", "")
local mpiroot = pathJoin("/usr/lib", multiarch, "openmpi")
setenv("GRF_OPENMPIROOT", "/usr")
setenv("GRF_OPENMPIINC", pathJoin(mpiroot, "include"))
setenv("GRF_OPENMPILIB", pathJoin(mpiroot, "lib"))
setenv("GRF_OPENMPIBIN", "/usr/bin")
setenv("GRF_OPENMPI_VERSION", myModuleVersion())
